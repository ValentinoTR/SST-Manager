import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const scope = text => text.replaceAll('sst_', 'ops_').replaceAll('sst-safety', 'ops-safety').replaceAll('sst-reports', 'ops-reports');
const segment = text => scope(text).replace(/^\s*(begin|commit);\s*$/gmi, '').replace(/^create extension .*;\r?\n/gm, '');
const base = segment(await read('supabase-modules.sql')).replaceAll('policy safety_', 'policy ops_safety_');
const state = `
-- Empty, independently owned roster. No INSERT ... SELECT from SST-Manager.
create table public.ops_app_state (
 user_id uuid primary key default auth.uid() references auth.users(id),
 payload jsonb not null default '{"workers":[]}'::jsonb,
 updated_at timestamptz not null default now()
);
alter table public.ops_app_state enable row level security;
revoke all on public.ops_app_state from public,anon,authenticated;
grant select,insert,update on public.ops_app_state to authenticated;
create policy read_own on public.ops_app_state for select to authenticated using(user_id=(select auth.uid()));
create policy insert_own on public.ops_app_state for insert to authenticated with check(user_id=(select auth.uid()) and (select public.ops_can_edit()));
create policy update_own on public.ops_app_state for update to authenticated using(user_id=(select auth.uid()) and (select public.ops_can_edit())) with check(user_id=(select auth.uid()) and (select public.ops_can_edit()));
create function ops_private.validate_workers() returns trigger language plpgsql security invoker set search_path='' as $$
declare worker jsonb; roster jsonb:=new.payload->'workers';
begin
 if jsonb_typeof(new.payload) is distinct from 'object' or jsonb_typeof(roster) is distinct from 'array' or new.payload-'workers'<>'{}'::jsonb then raise exception 'Estado de personal inválido'; end if;
 if tg_op='UPDATE' and new.user_id<>old.user_id then raise exception 'Propietario inmutable'; end if;
 if exists(select 1 from jsonb_array_elements(roster) w group by w->>'id' having count(*)>1) or exists(select 1 from jsonb_array_elements(roster) w group by w->>'dni' having count(*)>1) then raise exception 'DNI o identificador duplicado'; end if;
 for worker in select * from jsonb_array_elements(roster) loop
  if coalesce(worker->>'id','') !~ '^[A-Za-z0-9_-]{1,100}$' or coalesce(worker->>'dni','') !~ '^[0-9]{8}$' or coalesce(worker->>'status','') not in ('Activo','Inactivo') then raise exception 'Datos del trabajador inválidos'; end if;
  if not (length(trim(coalesce(worker->>'name',''))) between 1 and 200 and length(trim(coalesce(worker->>'role',''))) between 1 and 200 and length(trim(coalesce(worker->>'area',''))) between 1 and 200) then raise exception 'Completa nombre, cargo y área'; end if;
 end loop;
 if tg_op='UPDATE' then new.updated_at:=greatest(clock_timestamp(),old.updated_at+interval '1 microsecond'); else new.updated_at:=clock_timestamp(); end if;
 return new;
end $$;
revoke all on function ops_private.validate_workers() from public,anon,authenticated;
create trigger ops_validate_workers before insert or update on public.ops_app_state for each row execute function ops_private.validate_workers();
`;
