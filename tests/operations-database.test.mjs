import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import C from '../safety-core.js';
const user='10000000-0000-4000-8000-000000000001',other='10000000-0000-4000-8000-000000000002',vehicle='20000000-0000-4000-8000-000000000001';
const sql=path=>readFile(new URL('../'+path,import.meta.url),'utf8');
test('Operaciones: empieza vacía, separa registros y correo, aplica RLS y conserva SST-Manager',async()=>{
 const db=new PGlite();
 try {
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
 create schema auth;create schema storage;create schema cron;
 create function cron.schedule(text,text,text) returns bigint language sql as $$select 1::bigint$$;
 create table auth.users(id uuid primary key);insert into auth.users values('${user}'),('${other}');
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 create function auth.jwt() returns jsonb language sql stable as $$select jsonb_build_object('email','test@example.test')$$;
 grant usage on schema auth,storage,public to authenticated,anon,service_role;
 create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text);
 alter table storage.objects enable row level security;
 create function storage.foldername(text) returns text[] language sql immutable as $$select string_to_array($1,'/')$$;
 grant select,insert,update,delete on storage.objects to authenticated;
 create table public.sst_app_state(user_id uuid,payload jsonb);
 insert into public.sst_app_state values('${user}','{"workers":[{"id":"legacy"}],"medical":[{"id":"unchanged"}]}');`);
 for (const path of ['supabase-modules.sql','supabase-safety-history.sql','supabase/migrations/20261101174432_reliper_vehicle_template.sql','supabase/migrations/20261101203143_safety_critical_applicability.sql']) await db.exec(await sql(path));
 const asUser=async id=>db.exec(`reset role;select set_config('request.jwt.claim.sub','${id}',false);set role authenticated;`);
 await asUser(user);
 await db.query('insert into public.sst_vehicles(id,plate,type,brand,model) values($1,$2,$3,$4,$5)',[vehicle,'ABC123','Camioneta','Marca','Modelo']);
 await db.exec('reset role');
 const before=(await db.query('select payload from public.sst_app_state')).rows;
 await db.exec(await sql('supabase/migrations/20261108014132_operations_independent_records.sql'));
 await asUser(user);
 for (const table of ['app_state','vehicles','documents','document_versions','critical_defects','module_audit','report_jobs','mail_settings']) assert.equal((await db.query('select * from public.ops_'+table)).rows.length,0,table+' starts empty');
 await db.query('insert into public.ops_vehicles(id,plate,type,brand,model) values($1,$2,$3,$4,$5)',[vehicle,'ABC123','Camioneta','Marca nueva','Modelo nuevo']);
 const worker={id:'worker-new',name:'Ana Prueba',dni:'00123456',role:'Operadora',area:'Taller',status:'Activo'};
 await db.query('insert into public.ops_app_state(payload) values($1)',[{workers:[worker]}]);
 await assert.rejects(db.query('update public.ops_app_state set payload=$1',[{workers:[worker,{...worker,id:'worker-2'}]}]),/duplicado/);
 const first=(await db.query('select updated_at from public.ops_app_state')).rows[0].updated_at;
 await db.query('update public.ops_app_state set payload=$1 where updated_at=$2',[{workers:[{...worker,name:'Ana Corregida'}]},first]);
 assert.equal((await db.query('update public.ops_app_state set payload=$1 where updated_at=$2 returning *',[{workers:[]},first])).rows.length,0,'stale state cannot overwrite correction');
 assert.equal((await db.query("select * from public.ops_module_audit where entity='worker'")).rows.length,2);
 const payload={vehicleId:vehicle,items:C.checklist.map(c=>({...c,status:'Conforme',note:'',photo:null}))};
 payload.items[1].status='No conforme';payload.items[1].note='Freno sin presión';
 const doc='30000000-0000-4000-8000-000000000001';
 await db.query('select * from public.ops_save_document($1,$2,$3,$4,$5)',[doc,'inspection',payload,0,'Registro inicial']);
 assert.equal((await db.query('select aptitude from public.ops_vehicle_status')).rows[0].aptitude,'No apto');
 assert.equal((await db.query('select * from public.ops_critical_defects')).rows.length,1);
 const jobs=(await db.query('select * from public.ops_report_jobs')).rows;
 assert.equal(jobs.length,1);assert.equal(jobs[0].recipient,'seguridad@reliper.pe');
 assert.equal((await db.query('select * from public.sst_report_jobs')).rows.length,0);
 await db.query('insert into storage.objects(bucket_id,name) values($1,$2)',['sst-safety',user+'/evidence/old']);
 const defect=(await db.query('select id from public.ops_critical_defects')).rows[0].id;
 await assert.rejects(db.query('select public.ops_resolve_defect($1,$2,$3)',[defect,'Reparado y verificado',user+'/evidence/old']),/evidencia/);
 await db.query('insert into storage.objects(bucket_id,name) values($1,$2)',['ops-safety',user+'/evidence/new']);
 await db.query('select public.ops_resolve_defect($1,$2,$3)',[defect,'Reparado y verificado',user+'/evidence/new']);
 await assert.rejects(db.query('select * from ops_private.report_worker_auth'),/permission denied/);
 await assert.rejects(db.query('select public.ops_claim_report(null)'),/permission denied/);
 await asUser(other);
 assert.equal((await db.query('select * from public.ops_documents')).rows.length,0);
 assert.equal((await db.query('select * from public.ops_app_state')).rows.length,0);
 assert.equal((await db.query('select * from storage.objects')).rows.length,0);
 await db.exec(`reset role;insert into public.ops_module_roles values('${user}','viewer');`);await asUser(user);
 assert.equal((await db.query('update public.ops_app_state set payload=$1 returning *',[{workers:[]}])).rows.length,0,'viewer cannot update roster');
 await db.exec('reset role;set role service_role;');
 const claimed=(await db.query('select * from public.ops_claim_report(null)')).rows;
 assert.equal(claimed.length,1);assert.equal(claimed[0].document_id,doc);
 await db.exec('reset role');
 assert.deepEqual((await db.query('select payload from public.sst_app_state')).rows,before);
 assert.equal((await db.query('select brand from public.sst_vehicles')).rows[0].brand,'Marca');
 assert.equal((await db.query('select * from public.sst_documents')).rows.length,0);
 assert.equal((await db.query('select public from storage.buckets where id=$1',['ops-safety'])).rows[0].public,false);
 } finally { await db.close(); }
});
